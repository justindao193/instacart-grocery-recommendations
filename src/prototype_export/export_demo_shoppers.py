"""Connect the HTML demo to two small, checked historical examples. No training or answers."""
from pathlib import Path
import csv
import hashlib
import json
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / '02_Data/03_Model_Outputs/final_predictions.sqlite'
PAGE = ROOT / '03_Code/05_Prototype/grocery_recommendations_prototype.html'


def main():
    # Read the frozen history features without allowing database changes.
    connection = sqlite3.connect(DB.as_uri() + '?mode=ro', uri=True)
    connection.row_factory = sqlite3.Row
    assert connection.execute("SELECT value FROM build_metadata WHERE key='predictions_checked'").fetchone()[0] == 'passed'
    examples = {}
    audit = {}
    for alias, customer in [('A', 1), ('B', 113)]:
        rows = [dict(row) for row in connection.execute(
            'SELECT * FROM final_features WHERE user_id=? '
            'ORDER BY recency_score DESC,last_purchase_order DESC,product_id ASC', (customer,))]
        assert rows
        history = rows[0]['history_orders']
        assert all(0 < row['purchase_orders'] <= history and row['orders_since_last_purchase'] >= 0 for row in rows)
        ids = [row['product_id'] for row in rows]
        assert len(ids) == len(set(ids))
        frozen = [row[0] for row in connection.execute(
            "SELECT product_id FROM recommendations WHERE user_id=? AND method='weighted_recency' ORDER BY rank", (customer,))]
        assert ids[:5] == frozen, (alias, 'Saved top five differs')
        # Zero means bought in the latest known order; this isn't a day count.
        examples[alias] = {'orders': history, 'ranked': [
            [row['product_id'], row['purchase_orders'], row['orders_since_last_purchase']] for row in rows]}
        audit[alias] = {'source_user_id': customer, 'history_orders': history,
                       'candidate_count': len(rows), 'saved_top_five_match': True}
    popular = [row[0] for row in connection.execute(
        "SELECT product_id FROM recommendations WHERE method='popularity' AND user_id=1 ORDER BY rank")]
    assert len(popular) == 5
    connection.close()
    examples['C'] = {'orders': 0, 'ranked': [], 'simulated': True}

    # Look up exact names and aisles, keeping existing photos where available.
    page = PAGE.read_text(encoding='utf-8')
    original_styles = re.findall(r'<style\b[^>]*>.*?</style>', page, re.S)
    original_photos = re.search(r'const PHOTOS = (\{.*?\});', page, re.S)
    original_catalogue = re.search(r'const P = (\{.*?\n\});', page, re.S).group(1)
    existing = {int(key): json.loads(value) for key, value in re.findall(
        r'^\s*(\d+):(\[.*?\]),?\s*$', original_catalogue, re.M)}
    existing_ids = set(existing)
    wanted = existing_ids | set(popular) | {row[0] for value in examples.values() for row in value['ranked']}
    # Keep Claude's existing broad browsing groups instead of adding dozens of chips.
    # These are demo display groups, not the source dataset's exact aisle taxonomy.
    department_groups = {'7': 'drinks', '16': 'dairy', '17': 'household',
                         '3': 'bakery', '4': 'veg'}
    catalogue = {}
    labels = {}
    with (ROOT / '02_Data/01_Original/products.csv').open(encoding='utf-8', newline='') as handle:
        for row in csv.DictReader(handle):
            product_id = int(row['product_id'])
            if product_id in wanted:
                if product_id in existing:
                    key, photo = existing[product_id][1:]
                else:
                    key = 'fruit' if row['aisle_id'] == '24' else department_groups.get(row['department_id'], 'pantry')
                    photo = ''
                catalogue[product_id] = [row['product_name'], key, photo]
    assert set(catalogue) == wanted

    # Embed a small export so double-clicking the HTML needs no server or file fetch.
    payload = {'schema_version': 1, 'shoppers': examples, 'catalogue': catalogue,
               'aisles': labels, 'popular': popular,
               'notes': 'A/B are real historical examples. C is simulated. No final answers loaded.'}
    encode = lambda value: json.dumps(value, ensure_ascii=True, separators=(',', ':'))
    block = ('/* DEMO_DATA_START: generated by export_demo_shoppers.py */\n'
             + 'const DEMO_DATA = ' + encode(payload) + ';\n'
             + 'const SHOPPERS = DEMO_DATA.shoppers;\n'
             + 'Object.assign(P, DEMO_DATA.catalogue);\nObject.assign(AISLES, DEMO_DATA.aisles);\n'
             + 'const POPULAR = DEMO_DATA.popular;\n/* DEMO_DATA_END */')
    if '/* DEMO_DATA_START' in page:
        page, count = re.subn(r'/\* DEMO_DATA_START.*?/\* DEMO_DATA_END \*/', lambda _: block, page, flags=re.S)
    else:
        page, count = re.subn(r'const SHOPPERS = \{.*?const POPULAR = \[.*?\];', lambda _: block, page, count=1, flags=re.S)
    assert count == 1
    page = page.replace('Sample shopper histories', 'Real histories A/B · simulated C')
    page = page.replace('Shopper B · few past orders', 'Shopper B · short list')
    page = page.replace('Shopper C · no history', 'Shopper C · simulated new shopper')
    page = page.replace('if (it.ago===1)', 'if (it.ago===0)')
    page = page.replace('"buyagain-proto-hidden-"', '"buyagain-proto-real-v1-hidden-"')
    page = page.replace('Sample data: [product id, times bought, orders since last bought]. Counts only decide the small tags.',
                        'Real A/B: [product id, times bought, order positions since last bought]. Zero means last order. C is simulated.')
    page = page.replace('Real: product names, the ranking rule, the results, and the top five in the no-history list.',
                        'Real: product names, A/B purchase-history summaries and saved weighted-recency rankings, offline results, and the popularity list. All familiar candidates are available for Hide replacements.')
    page = re.sub(r'Sample: the example shoppers\x27 histories\. Photos are stock photos from Unsplash[^<]*',
                  'Simulated: shopper C has no history. Photos are illustrative stock photos from Unsplash, saved in this file. Unavailable images use a placeholder. This demo uses saved rankings; it does not retrain a model.', page)
    # New products without stock photography use the existing neutral placeholder.
    page = page.replace('<img src="${IMG(id)}" alt="" width="320" height="320" onerror="this.parentNode.classList.add(\'noimg\')">',
                        '${IMG(id) ? `<img src="${IMG(id)}" alt="" width="320" height="320" onerror="this.parentNode.classList.add(\'noimg\')">` : ""}')
    # Data/content integration must not redesign the approved page or replace its photos.
    assert re.findall(r'<style\b[^>]*>.*?</style>', page, re.S) == original_styles
    assert re.search(r'const PHOTOS = (\{.*?\});', page, re.S).group(0) == original_photos.group(0)
    PAGE.write_text(page, encoding='utf-8')
    (ROOT / '02_Data/03_Model_Outputs/demo_shoppers.json').write_text(
        json.dumps(payload, indent=2), encoding='utf-8')
    report = {'status': 'passed', 'examples': audit, 'C': 'simulated_no_history',
              'final_answers_read': False, 'models_refitted': False, 'frozen_predictions_modified': False,
              'all_candidates_exported': True, 'latest_order_gap': 0,
              'approved_styles_unchanged': True, 'existing_photos_unchanged': True,
              'style_sha256': hashlib.sha256(''.join(original_styles).encode()).hexdigest(),
              'display_groups': 'Existing broad demo categories retained; not exact source aisles.',
              'note': 'Local prototype examples, not representative users or usability evidence.'}
    (ROOT / '05_Results/03_Checks/demo_shopper_export.json').write_text(
        json.dumps(report, indent=2), encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
